function initialLocale(): Locale {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved === "zh-CN" || saved === "en") return saved;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export const locale = ref<Locale>(initialLocale());
export const localeLabel = computed(() =>
  locale.value === "zh-CN" ? zhCN["language.zhCN"] : en["language.en"],
);

export function setLocale(value: Locale): void {
  locale.value = value;
  localStorage.setItem(STORAGE_KEY, value);
  document.documentElement.lang = value;
  void syncNativeLocale();
}

export function toggleLocale(): void {
  setLocale(locale.value === "zh-CN" ? "en" : "zh-CN");
}

export function t(key: MessageKey, values: Record<string, string | number> = {}): string {
  const template = (locale.value === "zh-CN" ? zhCN : en)[key];
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export async function syncNativeLocale(): Promise<void> {
  await invoke("set_app_locale", { locale: locale.value });
}

document.documentElement.lang = locale.value;
